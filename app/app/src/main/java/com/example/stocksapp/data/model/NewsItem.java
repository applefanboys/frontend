package com.example.stocksapp.data.model;

public class NewsItem {
    private String title;
    private String url;
    private String source;
    private String time;

    public String getTitle() {
        return title;
    }

    public String getUrl() {
        return url;
    }

    public String getSource() {
        return source;
    }

    public String getTime() {
        return time;
    }
}
